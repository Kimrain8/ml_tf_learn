# 类别名 → 类别 ID（0 是"其他"）
PRODUCT_CLASS_NAMES = ['其他'] + list(PRODUCT_KEYWORDS.keys())
PRODUCT_CLASS_TO_ID = {name: i for i, name in enumerate(PRODUCT_CLASS_NAMES)}
NUM_PRODUCT_CLASSES = len(PRODUCT_CLASS_NAMES)

# 预编译关键词匹配表（类别 ID -> 关键词列表）
_KEYWORD_MAP = [
    (PRODUCT_CLASS_TO_ID[cls], kws)
    for cls, kws in PRODUCT_KEYWORDS.items()
]


def _clean_text(text):
    if not isinstance(text, str):
        return ''
    text = re.sub(r'\s+', '', text)
    return text


def classify_main_business(main_business, business_scope=None):
    """
    根据主营业务/经营范围文本返回产品类别 ID (0=其他)
    规则：每个类别的命中关键词数量为得分；最高分者胜出；平票取关键词总长度更长者
    """
    text = _clean_text(main_business) or _clean_text(business_scope)
    if not text:
        return 0

    scores = []
    for cls_id, keywords in _KEYWORD_MAP:
        hit = [kw for kw in keywords if kw in text]
        if not hit:
            continue
        # 得分 = (命中数量, 命中关键词总长度)，按元组字典序比较
        scores.append(((len(hit), sum(len(k) for k in hit)), cls_id))

    if not scores:
        return 0
    scores.sort(reverse=True)
    return scores[0][1]


def tokenize_for_tfidf(text):
    """用于 TF-IDF 的分词：过滤单字和标点，空格连接"""
    text = _clean_text(text)
    if not text:
        return '空'
    words = jieba.lcut(text)
    tokens = [w for w in words if len(w) >= 2 and not w.isdigit() and w.isalpha() or len(w) >= 3]
    return ' '.join(tokens) if tokens else '空'